export type ResponsiveImageAsset = {
  id: string;
  src: string;
  avifSrcSet: string;
  webpSrcSet: string;
  jpgSrcSet: string;
  width: number;
  height: number;
};

function createThreeStopAsset(
  id: string,
  avif: readonly [string, string, string],
  webp: readonly [string, string, string],
  jpg: readonly [string, string, string],
  width = 1200,
  height = 800,
): ResponsiveImageAsset {
  return {
    id,
    src: jpg[1],
    avifSrcSet: `${avif[0]} 480w, ${avif[1]} 800w, ${avif[2]} 1200w`,
    webpSrcSet: `${webp[0]} 480w, ${webp[1]} 800w, ${webp[2]} 1200w`,
    jpgSrcSet: `${jpg[0]} 480w, ${jpg[1]} 800w, ${jpg[2]} 1200w`,
    width,
    height,
  };
}

